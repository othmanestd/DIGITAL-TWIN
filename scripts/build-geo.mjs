// node scripts/build-geo.mjs
// Extracts the few shapes the geo scenes need from world-atlas into lib/geo/geodata.json (small, bundled).
// Territorial integrity: Morocco is ONE feature — the "Morocco" (504) and "W. Sahara" (732) geometries are merged
// with topojson.merge, so no internal border is ever drawn, at either resolution.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import * as topojson from "topojson-client";

const require = createRequire(import.meta.url);
const c50 = require("world-atlas/countries-50m.json");
const c110 = require("world-atlas/countries-110m.json");
const land110 = require("world-atlas/land-110m.json");

const round = (g) => {
  const r = (c) => (typeof c[0] === "number" ? [Math.round(c[0] * 1000) / 1000, Math.round(c[1] * 1000) / 1000] : c.map(r));
  return { ...g, coordinates: r(g.coordinates) };
};
const MA_IDS = new Set(["504", "732"]);

function moroccoOf(topo) {
  const geoms = topo.objects.countries.geometries.filter((g) => MA_IDS.has(g.id));
  if (geoms.length !== 2) throw new Error("Morocco / Sahara geometries not found");
  return { type: "Feature", id: "MA", properties: { name: "Maroc" }, geometry: round(topojson.merge(topo, geoms)) };
}

// Context neighbours for the Morocco map (drawn as dim low slabs). Clipped at render time by the projection.
const NEIGHBOURS = { "724": "Espagne", "620": "Portugal", "012": "Algérie", "478": "Mauritanie", "466": "Mali", "788": "Tunisie", "250": "France" };
const all50 = topojson.feature(c50, c50.objects.countries);
const neighbours = all50.features
  .filter((f) => NEIGHBOURS[f.id])
  .map((f) => ({ type: "Feature", id: f.id, properties: { name: NEIGHBOURS[f.id] }, geometry: round(f.geometry) }));

const out = {
  note: "Generated by scripts/build-geo.mjs from world-atlas (Natural Earth). Morocco = Morocco + southern provinces merged, no internal border.",
  morocco: moroccoOf(c50),
  moroccoLow: moroccoOf(c110),
  neighbours: { type: "FeatureCollection", features: neighbours },
  land: { type: "Feature", properties: {}, geometry: round(topojson.merge(land110, land110.objects.land.geometries)) },
};
const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "lib", "geo", "geodata.json");
writeFileSync(dest, JSON.stringify(out));
console.log("wrote", dest, (JSON.stringify(out).length / 1024).toFixed(0) + " KB", "neighbours:", neighbours.map((f) => f.properties.name).join(", "));
